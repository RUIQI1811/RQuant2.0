"""Locked membership of the oap_jq_cnc factor set.

oap_jq_cnc is every factor of oap, jq240, china_chars (484 candidates) with near duplicates removed. No return, Rank
IC or long-side information is used to pick members or to decide which duplicate survives:
- the absolute mean daily cross-sectional Spearman correlation of every pair was measured on the ``sh_main`` stores on
  every 5th trading date from 2008-05-12 to 2026-10-20 (897 dates; the full matrix of
  ``scripts/remove_duplicates/select_remove_duplicates.py``);
- factors are ordered by coverage (rounded to two decimals, higher first) and then by registry order (library in the
  order oap, jq240, china_chars, then ordinal);
- ``prune_correlated`` drops a factor when its correlation with an already kept factor reaches
  ``max_abs_rank_correlation`` (0.8). ``DEDUPLICATED`` maps each dropped factor to the kept one it duplicates.

Kept per source: oap 103 of 142, jq240 107 of 233, china_chars 44 of 109. Built with
``scripts/remove_duplicates/select_by_coverage.py``.

Members keep their source canonical names and values. ``direction`` is the sign of the sh_main 2020+ Rank IC and is
metadata only: it plays no part in membership and the stored column is not negated. Membership is meant for the
``sh_main`` universe, where the correlations were measured.
"""

