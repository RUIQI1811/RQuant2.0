"""Vendor the TA-Lib batch functions RQuant's talib factor set uses into one C++ header.

Usage: python scripts/vendor_ta_lib.py <ta-lib source checkout at tag v0.8.1>

The header (``src/rquant/factors/extensions/ta_lib/ta_lib.hpp``) holds the double-precision batch functions of the
TA-Lib C library, their lookback functions and the internal helpers they call, unchanged apart from being made
``static`` members of the ``rq_ta_lib`` namespace.  The KunQuant talib graph prepends it to its generated sources and
runs each function over every stock's own quotes, so factor values are those of TA-Lib itself.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from rquant.factors.libraries.talib_indicators import TALIB_INDICATORS  # noqa: E402

TARGET = ROOT / "src" / "rquant" / "factors" / "extensions" / "ta_lib" / "ta_lib.hpp"
DEFINITION = re.compile(
    r"^(?:TA_LIB_API\s+)?(?:static\s+)?(TA_RetCode|int|void|double)\s+(\w+)\s*\(", flags=re.M
)
STREAM_PARTS = ("_Stream", "Impl", "_Open", "_Update", "_Peek", "_Close", "_Value", "_OutRange", "_Advance", "_Clone")


def strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return "\n".join(line.rstrip() for line in text.splitlines() if line.strip())


def definitions(path: Path) -> dict[str, str]:
    """Top-level function definitions of one TA-Lib source file, by name."""
    text = strip_comments(path.read_text())
    found = {}
    for match in DEFINITION.finditer(text):
        name = match.group(2)
        end = text.index("\n}", match.start()) + 2
        found[name] = text[match.start() : end]
    return found


def main(source: Path) -> None:
    functions = source / "src" / "ta_func"
    catalog: dict[str, tuple[str, str]] = {}
    for path in sorted(functions.glob("ta_*.c")):
        for name, body in definitions(path).items():
            if name.startswith("TA_S_") or any(part in name for part in STREAM_PARTS):
                continue
            catalog.setdefault(name, (path.name, body))
    wanted = sorted({function for _, function, *_ in TALIB_INDICATORS})
    selected: dict[str, str] = {}
    pending = [name for function in wanted for name in (f"TA_{function}", f"TA_{function}_Lookback")]
    while pending:
        name = pending.pop()
        if name in selected:
            continue
        if name not in catalog:
            raise SystemExit(f"TA-Lib function {name} not found")
        body = catalog[name][1]
        selected[name] = body
        for called in re.findall(r"\b(TA_\w+)\s*\(", body[body.index("{") :]):
            if called in catalog and called not in selected:
                pending.append(called)
    ordered = sorted(selected, key=lambda name: (catalog[name][0], name))
    prototypes = []
    bodies = []
    for name in ordered:
        body = selected[name]
        body = re.sub(r"^(?:TA_LIB_API\s+)?(?:static\s+)?", "static inline ", body, count=1)
        # C converts malloc's void * implicitly; route the calls through TA_Malloc's C++ proxy.
        body = re.sub(r"(?<![\w.])malloc\(", "TA_Malloc(", body)
        bodies.append(f"/* {catalog[name][0]} */\n{body}")
        prototypes.append(body[: body.index("{")].rstrip() + ";")
    compat = (ROOT / "scripts" / "ta_lib_compat.hpp").read_text()
    head, tail = compat.split("/* @FUNCTIONS@ */")
    license_text = (source / "LICENSE").read_text()
    text = (
        "/* Generated by scripts/vendor_ta_lib.py from TA-Lib 0.8.1 (https://github.com/TA-Lib/ta-lib); do not edit.\n"
        + "\n".join(f" * {line}".rstrip() for line in license_text.splitlines())
        + "\n */\n"
        + head
        + "\n".join(prototypes)
        + "\n\n"
        + "\n\n".join(bodies)
        + "\n"
        + tail
    )
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text)
    print(f"wrote {TARGET} with {len(selected)} functions")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
